const fmtPct = (n: number, decimals = 2) => `${n.toFixed(decimals)}%`;

// ─── freelancer tax calculation utilities ─────────────────────────────────────

// 2024 Tax Constants
const SOCIAL_SECURITY_WAGE_BASE = 168600; // 2024 wage base
const STANDARD_DEDUCTION = 14600; // Single filer

// 2024 Federal Income Tax Brackets (Single)
const TAX_BRACKETS = [
  { min: 0, max: 11600, rate: 0.10 },
  { min: 11600, max: 47150, rate: 0.12 },
  { min: 47150, max: 100525, rate: 0.22 },
  { min: 100525, max: 191950, rate: 0.24 },
  { min: 191950, max: 243725, rate: 0.32 },
  { min: 243725, max: 609350, rate: 0.35 },
  { min: 609350, max: Infinity, rate: 0.37 },
];

function calculateFederalIncomeTax(taxableIncome: number): number {
  if (taxableIncome <= 0) return 0;

  let tax = 0;
  let remainingIncome = taxableIncome;

  for (const bracket of TAX_BRACKETS) {
    if (remainingIncome <= 0) break;

    const taxableInBracket = Math.min(
      remainingIncome,
      bracket.max - bracket.min
    );
    tax += taxableInBracket * bracket.rate;
    remainingIncome -= taxableInBracket;
  }

  return tax;
}

function calculateFreelancerTaxes(
  grossIncome: number,
  businessExpenses: number
) {
  // Calculate net earnings from self-employment
  const netEarnings = Math.max(0, grossIncome - businessExpenses);

  // Calculate self-employment tax
  // Social Security (12.4%) applies only up to wage base
  const socialSecurityWageBase = SOCIAL_SECURITY_WAGE_BASE;
  const socialSecurityTaxable = Math.min(netEarnings * 0.9235, socialSecurityWageBase); // 92.35% of net earnings
  const socialSecurityTax = socialSecurityTaxable * 0.124;

  // Medicare (2.9%) applies to all net earnings
  const medicareTax = netEarnings * 0.9235 * 0.029;

  const selfEmploymentTax = socialSecurityTax + medicareTax;
  const deductibleSelfEmploymentTax = selfEmploymentTax * 0.5; // 50% deductible

  // Calculate taxable income for federal income tax
  const taxableIncome = Math.max(0, netEarnings - deductibleSelfEmploymentTax - STANDARD_DEDUCTION);

  // Calculate federal income tax
  const federalIncomeTax = calculateFederalIncomeTax(taxableIncome);

  // Total tax liability
  const totalTax = selfEmploymentTax + federalIncomeTax;

  // Effective tax rate
  const effectiveTaxRate = netEarnings > 0 ? (totalTax / netEarnings) * 100 : 0;

  // Estimated quarterly payments
  const quarterlyPayment = totalTax / 4;

  // Net income after taxes
  const netIncome = netEarnings - totalTax;

  // Tax savings from business expenses
  const expenseTaxSavings = businessExpenses * 0.153; // Self-employment tax savings

  return {
    grossIncome,
    businessExpenses,
    netEarnings,
    selfEmploymentTax,
    socialSecurityTax,
    medicareTax,
    deductibleSelfEmploymentTax,
    taxableIncome,
    federalIncomeTax,
    totalTax,
    effectiveTaxRate,
    quarterlyPayment,
    netIncome,
    expenseTaxSavings,
  };
}

// ─── input components ────────────────────────────────────────────────────────────

function InputField({
  label,
  value,
  onChange,
  prefix = "",
  suffix = "",
  step = "1",
  min = "0",
  helper = "",
  type = "number",
}: {
  label: string;
  value: number | string;
  onChange: (value: number) => void;
  prefix?: string;
  suffix?: string;
  step?: string;
  min?: string;
  helper?: string;
  type?: string;
}) {
  const inputId = label.toLowerCase().replace(/\s+/g, "-");
  return (
    <div className="space-y-1.5">
      <label
        htmlFor={inputId}
        className="text-xs font-semibold text-slate-800 dark:text-slate-400 uppercase tracking-wide"
      >
        {label}
        {helper && (
          <span className="ml-2 font-normal text-slate-400 dark:text-slate-400 normal-case">
            ({helper})
          </span>
        )}
      </label>
      <div className="relative">
        {prefix && (
          <span
            className="absolute left-3 top-1/2 -translate-y-1/2 text-slate-500 dark:text-slate-400 font-medium"
            aria-hidden="true"
          >
            {prefix}
          </span>
        )}
        <input
          id={inputId}
          type={type}
          value={value}
          min={min}
          step={step}
          onChange={(e) => onChange(Number(e.target.value))}
          aria-label={label}
          className={`w-full bg-slate-50 dark:bg-slate-900/50 border border-slate-200 dark:border-slate-800 rounded-xl px-3 py-2.5 text-sm font-medium text-slate-800 dark:text-slate-100 outline-none focus:ring-2 focus:ring-emerald-500 focus:border-transparent transition-all ${prefix ? "pl-8" : ""} ${suffix ? "pr-8" : ""}`}
        />
        {suffix && (
          <span
            className="absolute right-3 top-1/2 -translate-y-1/2 text-slate-500 dark:text-slate-400 font-medium"
            aria-hidden="true"
          >
            {suffix}
          </span>
        )}
      </div>
    </div>
  );
}

